import { useCallback, useEffect, useRef, useState } from 'react';
import {
  AccessibilityInfo,
  Animated,
  Easing,
  Image,
  ImageRequireSource,
  Pressable,
  StyleSheet,
  View,
} from 'react-native';

/**
 * The seven frames every mascot pack generates, in engine frame-name order:
 * idle, blink, look, walk_a, walk_b, happy, surprised (camelCased here).
 */
export type PixelPetFrames = {
  idle: ImageRequireSource;
  blink: ImageRequireSource;
  look: ImageRequireSource;
  walkA: ImageRequireSource;
  walkB: ImageRequireSource;
  happy: ImageRequireSource;
  surprised: ImageRequireSource;
};

export type PixelPetParticles = {
  star: ImageRequireSource;
  heart: ImageRequireSource;
};

/** One manifest v2 cycle (`cycles.<name>`): fps + its rendered frame PNGs. */
export type PixelPetCycle = {
  /** Frames per second from the pack manifest (`cycles.<name>.fps`). */
  fps: number;
  /** Cycle frames in manifest order, as static Metro `require()` literals. */
  frames: ImageRequireSource[];
};

/** Manifest v2 cycle playback sources. Omit on v1 packs — behavior unchanged. */
export type PixelPetCycles = { walk?: PixelPetCycle };

type FrameName = keyof PixelPetFrames;
type Mood = 'idle' | 'walk' | 'celebrate';

const WALK_MS = 2600;
const POKE_MS = 550;

// Behavior scheduler (motion spec #17): idle behaviors are mutually exclusive,
// randomized, and never overlap. The shuffle borrows the canonical walk frames.
const BLINK_GAP_MS: [number, number] = [2600, 4800];
const BLINK_HOLD_MS = 140;
const LOOK_GAP_MS: [number, number] = [6000, 10000];
const LOOK_HOLD_MS: [number, number] = [600, 900];
const SHUFFLE_CHANCE = 0.35; // rolled after each look
const SHUFFLE_DELAY_MS: [number, number] = [1200, 4000];
const SHUFFLE_HOLD_MS = 300; // per frame: walk_a → walk_b → walk_a
const SHUFFLE_COOLDOWN_MS = 8000;

type PixelPetProps = {
  /** Frame sources from a mascot pack (assets generated by the engine). */
  frames: PixelPetFrames;
  particles: PixelPetParticles;
  /** 0..1 goal progress. Rising progress → walk; ≥ 1 → celebrate. */
  progress: number;
  /** Manifest v2 cycle sources; a v1 pack omits it (two-frame walk swap). */
  cycles?: PixelPetCycles;
  size?: number;
};

/**
 * A pixel mascot driven by a mood state machine: idle (bob + scheduled
 * behaviors), walk on progress increases, celebrate at progress ≥ 1, and a
 * surprised hop (plus heart) when poked. Poses change by frame swap; soft
 * motion (bob, tilt, squash) runs on native-driven transforms.
 *
 * Manifest v2 packs pass `cycles` and the walk mood plays their cycle at the
 * manifest fps; v1 packs omit it and keep the two-frame walk swap. Under
 * Reduce Motion, transforms freeze at rest — bounded frame swaps (blink, look,
 * shuffle, walk cycle) and bounded moods still play.
 */
export default function PixelPet({
  frames,
  particles,
  progress,
  cycles,
  size = 170,
}: PixelPetProps) {
  const [mood, setMood] = useState<Mood>(progress >= 1 ? 'celebrate' : 'idle');
  const [idleFrame, setIdleFrame] = useState<FrameName>('idle');
  const [walkFrame, setWalkFrame] = useState<'walkA' | 'walkB'>('walkA');
  const [cycleIndex, setCycleIndex] = useState(0);
  const [poked, setPoked] = useState(false);
  const [heartKey, setHeartKey] = useState(0);
  const [reduceMotion, setReduceMotion] = useState(false);

  const walkCycle = cycles?.walk;
  // Latest-ref: the interval reads the current cycle each tick, so consumers
  // passing an inline `cycles` object don't restart playback on re-render.
  const walkCycleRef = useRef(walkCycle);
  useEffect(() => {
    walkCycleRef.current = walkCycle;
  });

  const prevProgress = useRef(progress);
  const bobY = useRef(new Animated.Value(0)).current;
  const tilt = useRef(new Animated.Value(0)).current;
  const squash = useRef(new Animated.Value(1)).current;
  const pokePunch = useRef(new Animated.Value(1)).current;
  const heart = useRef(new Animated.Value(0)).current;

  // --- Reduce Motion ----------------------------------------------------------

  useEffect(() => {
    let live = true;
    AccessibilityInfo.isReduceMotionEnabled().then(
      (v) => {
        if (live) setReduceMotion(v);
      },
      () => {}
    );
    const sub = AccessibilityInfo.addEventListener('reduceMotionChanged', setReduceMotion);
    return () => {
      live = false;
      sub.remove();
    };
  }, []);

  // --- mood state machine ----------------------------------------------------

  useEffect(() => {
    if (progress >= 1) {
      setMood('celebrate');
    } else if (progress > prevProgress.current) {
      setMood('walk');
    } else if (progress < prevProgress.current && mood === 'walk') {
      setMood('idle');
    }
    prevProgress.current = progress;
  }, [progress, mood]);

  // walk bursts settle back into idle
  useEffect(() => {
    if (mood !== 'walk') return;
    const t = setTimeout(() => setMood('idle'), WALK_MS);
    return () => clearTimeout(t);
  }, [mood]);

  // --- walk frame playback -----------------------------------------------------

  useEffect(() => {
    if (mood !== 'walk') return;
    if (!walkCycle || walkCycle.frames.length === 0) {
      // v1 pack: the two-frame walk swap, unchanged
      const swap = setInterval(
        () => setWalkFrame((f) => (f === 'walkA' ? 'walkB' : 'walkA')),
        180
      );
      return () => clearInterval(swap);
    }
    // manifest v2: the walk cycle at the manifest fps
    setCycleIndex(0);
    const step = Math.max(16, Math.round(1000 / Math.max(1, walkCycle.fps)));
    const interval = setInterval(() => {
      const cycle = walkCycleRef.current;
      if (!cycle || cycle.frames.length === 0) return;
      setCycleIndex((i) => (i + 1) % cycle.frames.length);
    }, step);
    return () => clearInterval(interval);
  }, [mood, walkCycle?.fps, walkCycle?.frames.length]);

  // --- behavior scheduler --------------------------------------------------------

  useEffect(() => {
    if (mood !== 'idle') return;

    let blinkTimer: ReturnType<typeof setTimeout>;
    let lookTimer: ReturnType<typeof setTimeout>;
    let seqTimer: ReturnType<typeof setTimeout>;
    let shuffleTimer: ReturnType<typeof setTimeout>;
    let shuffledAt = -Infinity;
    let busy = false;

    const rand = ([lo, hi]: [number, number]) => lo + Math.random() * (hi - lo);

    // Play one behavior's frame sequence; the busy flag keeps behaviors
    // mutually exclusive — a timer firing mid-behavior re-rolls instead.
    const playSequence = (seq: FrameName[], holdMs: number, after?: () => void) => {
      busy = true;
      let i = 0;
      const step = () => {
        if (i >= seq.length) {
          setIdleFrame('idle');
          busy = false;
          after?.();
          return;
        }
        setIdleFrame(seq[i]);
        i += 1;
        seqTimer = setTimeout(step, holdMs);
      };
      step();
    };

    const scheduleBlink = (delay: number) => {
      blinkTimer = setTimeout(() => {
        if (!busy) playSequence(['blink'], BLINK_HOLD_MS, () => scheduleBlink(rand(BLINK_GAP_MS)));
        else scheduleBlink(rand(BLINK_GAP_MS));
      }, delay);
    };

    const scheduleLook = (delay: number) => {
      lookTimer = setTimeout(() => {
        if (busy) {
          scheduleLook(rand(LOOK_GAP_MS));
          return;
        }
        playSequence(['look'], rand(LOOK_HOLD_MS), () => {
          scheduleLook(rand(LOOK_GAP_MS));
          maybeShuffle();
        });
      }, delay);
    };

    const maybeShuffle = () => {
      if (Math.random() >= SHUFFLE_CHANCE) return;
      const delay = rand(SHUFFLE_DELAY_MS);
      if (Date.now() + delay < shuffledAt + SHUFFLE_COOLDOWN_MS) return;
      shuffleTimer = setTimeout(() => {
        if (busy) return;
        playSequence(['walkA', 'walkB', 'walkA'], SHUFFLE_HOLD_MS, () => {
          shuffledAt = Date.now();
        });
      }, delay);
    };

    // A walk burst can interrupt a behavior mid-sequence; start from rest.
    setIdleFrame('idle');
    scheduleBlink(rand(BLINK_GAP_MS));
    scheduleLook(rand(LOOK_GAP_MS));
    return () => {
      clearTimeout(blinkTimer);
      clearTimeout(lookTimer);
      clearTimeout(seqTimer);
      clearTimeout(shuffleTimer);
    };
  }, [mood]);

  // --- motion drivers ----------------------------------------------------------

  useEffect(() => {
    if (reduceMotion) return; // transforms stay frozen at rest
    const animations: Animated.CompositeAnimation[] = [];
    const play = (a: Animated.CompositeAnimation) => {
      animations.push(a);
      a.start();
    };
    if (mood === 'idle') {
      play(
        Animated.loop(
          Animated.sequence([
            Animated.timing(bobY, {
              toValue: -5,
              duration: 1100,
              easing: Easing.inOut(Easing.quad),
              useNativeDriver: true,
            }),
            Animated.timing(bobY, {
              toValue: 0,
              duration: 1100,
              easing: Easing.inOut(Easing.quad),
              useNativeDriver: true,
            }),
          ])
        )
      );
    } else if (mood === 'walk') {
      play(
        Animated.loop(
          Animated.sequence([
            Animated.timing(bobY, {
              toValue: -7,
              duration: 200,
              easing: Easing.out(Easing.quad),
              useNativeDriver: true,
            }),
            Animated.timing(bobY, {
              toValue: 0,
              duration: 180,
              easing: Easing.in(Easing.quad),
              useNativeDriver: true,
            }),
          ])
        )
      );
      play(
        Animated.loop(
          Animated.sequence([
            Animated.timing(tilt, {
              toValue: 4,
              duration: 190,
              useNativeDriver: true,
            }),
            Animated.timing(tilt, {
              toValue: -4,
              duration: 190,
              useNativeDriver: true,
            }),
          ])
        )
      );
    } else {
      // celebrate: hop + squash-and-stretch on landing; volume preserved
      // (scaleX up while scaleY down) so the body reads as squishy, not flat
      play(
        Animated.loop(
          Animated.sequence([
            Animated.timing(bobY, {
              toValue: -18,
              duration: 260,
              easing: Easing.out(Easing.quad),
              useNativeDriver: true,
            }),
            Animated.timing(bobY, {
              toValue: 0,
              duration: 230,
              easing: Easing.in(Easing.quad),
              useNativeDriver: true,
            }),
            Animated.parallel([
              Animated.timing(squash, {
                toValue: 1.12,
                duration: 90,
                useNativeDriver: true,
              }),
              Animated.timing(bobY, {
                toValue: 3,
                duration: 90,
                useNativeDriver: true,
              }),
            ]),
            Animated.timing(squash, {
              toValue: 1,
              duration: 220,
              easing: Easing.out(Easing.elastic(2)),
              useNativeDriver: true,
            }),
            Animated.timing(bobY, {
              toValue: 0,
              duration: 260,
              useNativeDriver: true,
            }),
          ])
        )
      );
    }
    return () => {
      animations.forEach((a) => a.stop());
      bobY.setValue(0);
      tilt.setValue(0);
      squash.setValue(1);
    };
  }, [mood, reduceMotion, bobY, tilt, squash]);

  // --- poke --------------------------------------------------------------------

  const handlePoke = useCallback(() => {
    setPoked(true);
    setHeartKey((k) => k + 1);
    heart.setValue(0);
    const feedback: Animated.CompositeAnimation[] = [
      Animated.timing(heart, {
        toValue: 1,
        duration: 750,
        easing: Easing.out(Easing.quad),
        useNativeDriver: true,
      }),
    ];
    if (!reduceMotion) {
      feedback.push(
        Animated.sequence([
          Animated.spring(pokePunch, {
            toValue: 1.14,
            friction: 3,
            tension: 200,
            useNativeDriver: true,
          }),
          Animated.spring(pokePunch, {
            toValue: 1,
            friction: 4,
            tension: 160,
            useNativeDriver: true,
          }),
        ])
      );
    }
    Animated.parallel(feedback).start();
    setTimeout(() => setPoked(false), POKE_MS);
  }, [heart, pokePunch, reduceMotion]);

  // --- render --------------------------------------------------------------------

  const cycleSource: ImageRequireSource | null =
    !poked && mood === 'walk' && walkCycle && walkCycle.frames.length > 0
      ? walkCycle.frames[cycleIndex % walkCycle.frames.length]
      : null;

  const frame: FrameName = poked
    ? 'surprised'
    : mood === 'celebrate'
      ? 'happy'
      : mood === 'walk'
        ? walkFrame
        : idleFrame;

  return (
    <Pressable onPress={handlePoke} hitSlop={20}>
      <View style={{ width: size, height: size, alignItems: 'center', justifyContent: 'center' }}>
        {mood === 'celebrate' && <Sparkles size={size} star={particles.star} reduceMotion={reduceMotion} />}
        {heartKey > 0 && (
          <Animated.Image
            key={heartKey}
            source={particles.heart}
            style={[
              styles.heart,
              {
                width: size * 0.2,
                height: size * 0.2 * (6 / 7),
                opacity: heart.interpolate({
                  inputRange: [0, 0.25, 1],
                  outputRange: [0, 1, 0],
                }),
                // Reduce Motion: opacity feedback stays, the rise freezes
                ...(reduceMotion
                  ? {}
                  : {
                      transform: [
                        {
                          translateY: heart.interpolate({
                            inputRange: [0, 1],
                            outputRange: [-size * 0.15, -size * 0.6],
                          }),
                        },
                      ],
                    }),
              },
            ]}
          />
        )}
        <Animated.View
          style={{
            transform: [
              { translateY: bobY },
              { rotate: tilt.interpolate({ inputRange: [-4, 4], outputRange: ['-4deg', '4deg'] }) },
              { scale: pokePunch },
              { scaleX: squash },
              { scaleY: squash.interpolate({ inputRange: [1, 1.12], outputRange: [1, 0.9] }) },
            ],
          }}
        >
          <Image
            source={cycleSource ?? frames[frame]}
            style={{ width: size, height: size }}
            resizeMode="contain"
            fadeDuration={0}
          />
        </Animated.View>
      </View>
    </Pressable>
  );
}

/** Rising, twinkling stars shown behind the pet while it celebrates. */
function Sparkles({
  size,
  star,
  reduceMotion,
}: {
  size: number;
  star: ImageRequireSource;
  reduceMotion: boolean;
}) {
  const stars = useRef(
    Array.from({ length: 5 }, (_, i) => ({
      left: 8 + i * 19,
      delay: i * 320,
      drift: (i % 2 === 0 ? 1 : -1) * 14,
      anim: new Animated.Value(0),
    }))
  ).current;

  useEffect(() => {
    const loops = stars.map(({ anim, delay }) => {
      const loop = Animated.loop(
        Animated.sequence([
          Animated.delay(delay),
          Animated.timing(anim, {
            toValue: 1,
            duration: 1700,
            easing: Easing.linear,
            useNativeDriver: true,
          }),
          Animated.timing(anim, { toValue: 0, duration: 0, useNativeDriver: true }),
        ])
      );
      loop.start();
      return loop;
    });
    return () => loops.forEach((l) => l.stop());
  }, [stars]);

  return (
    <View style={[styles.sparkleLayer, { width: size, height: size }]} pointerEvents="none">
      {stars.map(({ anim, left, drift }, i) => (
        <Animated.Image
          key={i}
          source={star}
          style={[
            styles.star,
            {
              left: left as number,
              width: size * 0.13,
              height: size * 0.13,
              opacity: anim.interpolate({ inputRange: [0, 0.2, 0.8, 1], outputRange: [0, 1, 1, 0] }),
              // Reduce Motion: twinkle in place, no drift
              ...(reduceMotion
                ? {}
                : {
                    transform: [
                      {
                        translateY: anim.interpolate({ inputRange: [0, 1], outputRange: [0, -size * 0.55] }),
                      },
                      {
                        translateX: anim.interpolate({ inputRange: [0, 1], outputRange: [0, drift] }),
                      },
                    ],
                  }),
            },
          ]}
        />
      ))}
    </View>
  );
}

const styles = StyleSheet.create({
  sparkleLayer: {
    position: 'absolute',
  },
  star: {
    position: 'absolute',
    bottom: '18%',
  },
  heart: {
    position: 'absolute',
    top: 0,
    zIndex: 1,
  },
});
