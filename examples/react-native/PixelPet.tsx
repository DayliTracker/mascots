import { useCallback, useEffect, useRef, useState } from 'react';
import {
  Animated,
  Easing,
  Image,
  ImageRequireSource,
  Pressable,
  StyleSheet,
  View,
} from 'react-native';

/**
 * The seven frames every mascot pack generates, in engine frame-name order:
 * idle, blink, look, walk_a, walk_b, happy, surprised (camelCased here).
 */
export type PixelPetFrames = {
  idle: ImageRequireSource;
  blink: ImageRequireSource;
  look: ImageRequireSource;
  walkA: ImageRequireSource;
  walkB: ImageRequireSource;
  happy: ImageRequireSource;
  surprised: ImageRequireSource;
};

export type PixelPetParticles = {
  star: ImageRequireSource;
  heart: ImageRequireSource;
};

type FrameName = keyof PixelPetFrames;
type Mood = 'idle' | 'walk' | 'celebrate';

const WALK_MS = 2600;
const POKE_MS = 550;

type PixelPetProps = {
  /** Frame sources from a mascot pack (assets generated by the engine). */
  frames: PixelPetFrames;
  particles: PixelPetParticles;
  /** 0..1 goal progress. Rising → walk; ≥ 1 → celebrate; below 1 → idle. */
  progress: number;
  size?: number;
};

/**
 * A pixel mascot driven by a mood state machine: idle (bob + blink + glance
 * around), walk on progress increases, celebrate at progress ≥ 1, and a
 * surprised hop (plus heart) when poked. Poses change by frame swap; soft
 * motion (bob, tilt, squash) runs on native-driven transforms.
 */
export default function PixelPet({ frames, particles, progress, size = 170 }: PixelPetProps) {
  const [mood, setMood] = useState<Mood>(progress >= 1 ? 'celebrate' : 'idle');
  const [idleFrame, setIdleFrame] = useState<FrameName>('idle');
  const [walkFrame, setWalkFrame] = useState<'walkA' | 'walkB'>('walkA');
  const [poked, setPoked] = useState(false);
  const [heartKey, setHeartKey] = useState(0);

  const prevProgress = useRef(progress);
  const bobY = useRef(new Animated.Value(0)).current;
  const tilt = useRef(new Animated.Value(0)).current;
  const squash = useRef(new Animated.Value(1)).current;
  const pokePunch = useRef(new Animated.Value(1)).current;
  const heart = useRef(new Animated.Value(0)).current;

  // --- mood state machine ----------------------------------------------------

  useEffect(() => {
    if (progress >= 1) {
      setMood('celebrate');
    } else if (progress > prevProgress.current) {
      setMood('walk');
    } else if (mood === 'walk' || mood === 'celebrate') {
      // progress fell (or held) below 1 — e.g. a new day reset the goal;
      // celebrate must exit or the pet celebrates forever
      setMood('idle');
    }
    prevProgress.current = progress;
  }, [progress, mood]);

  // walk bursts settle back into idle
  useEffect(() => {
    if (mood !== 'walk') return;
    const t = setTimeout(() => setMood('idle'), WALK_MS);
    return () => clearTimeout(t);
  }, [mood]);

  // --- frame timers ----------------------------------------------------------

  useEffect(() => {
    if (mood === 'walk') {
      const swap = setInterval(
        () =>
          setWalkFrame((f) => (f === 'walkA' ? 'walkB' : 'walkA')),
        180
      );
      return () => clearInterval(swap);
    }
    if (mood !== 'idle') return;

    let blinkTimer: ReturnType<typeof setTimeout>;
    let lookTimer: ReturnType<typeof setTimeout>;
    let restoreTimer: ReturnType<typeof setTimeout>;
    const scheduleBlink = () => {
      blinkTimer = setTimeout(() => {
        setIdleFrame('blink');
        restoreTimer = setTimeout(() => setIdleFrame('idle'), 150);
        scheduleBlink();
      }, 2600 + Math.random() * 2200);
    };
    const scheduleLook = () => {
      lookTimer = setTimeout(() => {
        setIdleFrame('look');
        restoreTimer = setTimeout(() => setIdleFrame('idle'), 700);
        scheduleLook();
      }, 6000 + Math.random() * 4000);
    };
    scheduleBlink();
    scheduleLook();
    return () => {
      clearTimeout(blinkTimer);
      clearTimeout(lookTimer);
      clearTimeout(restoreTimer);
      // a mood change can fire mid-blink/mid-look, killing the pending
      // restore timer — reset so idle doesn't resume holding the wrong face
      setIdleFrame('idle');
    };
  }, [mood]);

  // --- motion drivers ----------------------------------------------------------

  useEffect(() => {
    const animations: Animated.CompositeAnimation[] = [];
    const play = (a: Animated.CompositeAnimation) => {
      animations.push(a);
      a.start();
    };
    if (mood === 'idle') {
      play(
        Animated.loop(
          Animated.sequence([
            Animated.timing(bobY, {
              toValue: -5,
              duration: 1100,
              easing: Easing.inOut(Easing.quad),
              useNativeDriver: true,
            }),
            Animated.timing(bobY, {
              toValue: 0,
              duration: 1100,
              easing: Easing.inOut(Easing.quad),
              useNativeDriver: true,
            }),
          ])
        )
      );
    } else if (mood === 'walk') {
      play(
        Animated.loop(
          Animated.sequence([
            Animated.timing(bobY, {
              toValue: -7,
              duration: 200,
              easing: Easing.out(Easing.quad),
              useNativeDriver: true,
            }),
            Animated.timing(bobY, {
              toValue: 0,
              duration: 180,
              easing: Easing.in(Easing.quad),
              useNativeDriver: true,
            }),
          ])
        )
      );
      play(
        Animated.loop(
          Animated.sequence([
            Animated.timing(tilt, {
              toValue: 4,
              duration: 190,
              useNativeDriver: true,
            }),
            Animated.timing(tilt, {
              toValue: -4,
              duration: 190,
              useNativeDriver: true,
            }),
          ])
        )
      );
    } else {
      // celebrate: hop + squash-and-stretch on landing; volume preserved
      // (scaleX up while scaleY down) so the body reads as squishy, not flat
      play(
        Animated.loop(
          Animated.sequence([
            Animated.timing(bobY, {
              toValue: -18,
              duration: 260,
              easing: Easing.out(Easing.quad),
              useNativeDriver: true,
            }),
            Animated.timing(bobY, {
              toValue: 0,
              duration: 230,
              easing: Easing.in(Easing.quad),
              useNativeDriver: true,
            }),
            Animated.parallel([
              Animated.timing(squash, {
                toValue: 1.12,
                duration: 90,
                useNativeDriver: true,
              }),
              Animated.timing(bobY, {
                toValue: 3,
                duration: 90,
                useNativeDriver: true,
              }),
            ]),
            Animated.timing(squash, {
              toValue: 1,
              duration: 220,
              easing: Easing.out(Easing.elastic(2)),
              useNativeDriver: true,
            }),
            Animated.timing(bobY, {
              toValue: 0,
              duration: 260,
              useNativeDriver: true,
            }),
          ])
        )
      );
    }
    return () => {
      animations.forEach((a) => a.stop());
      bobY.setValue(0);
      tilt.setValue(0);
      squash.setValue(1);
    };
  }, [mood, bobY, tilt, squash]);

  // --- poke --------------------------------------------------------------------

  const handlePoke = useCallback(() => {
    setPoked(true);
    setHeartKey((k) => k + 1);
    heart.setValue(0);
    Animated.parallel([
      Animated.timing(heart, {
        toValue: 1,
        duration: 750,
        easing: Easing.out(Easing.quad),
        useNativeDriver: true,
      }),
      Animated.sequence([
        Animated.spring(pokePunch, {
          toValue: 1.14,
          friction: 3,
          tension: 200,
          useNativeDriver: true,
        }),
        Animated.spring(pokePunch, {
          toValue: 1,
          friction: 4,
          tension: 160,
          useNativeDriver: true,
        }),
      ]),
    ]).start();
    setTimeout(() => setPoked(false), POKE_MS);
  }, [heart, pokePunch]);

  // --- render --------------------------------------------------------------------

  const frame: FrameName = poked
    ? 'surprised'
    : mood === 'celebrate'
      ? 'happy'
      : mood === 'walk'
        ? walkFrame
        : idleFrame;

  return (
    <Pressable onPress={handlePoke} hitSlop={20}>
      <View style={{ width: size, height: size, alignItems: 'center', justifyContent: 'center' }}>
        {mood === 'celebrate' && <Sparkles size={size} star={particles.star} />}
        {heartKey > 0 && (
          <Animated.Image
            key={heartKey}
            source={particles.heart}
            style={[
              styles.heart,
              {
                width: size * 0.2,
                height: size * 0.2 * (6 / 7),
                opacity: heart.interpolate({
                  inputRange: [0, 0.25, 1],
                  outputRange: [0, 1, 0],
                }),
                transform: [
                  {
                    translateY: heart.interpolate({
                      inputRange: [0, 1],
                      outputRange: [-size * 0.15, -size * 0.6],
                    }),
                  },
                ],
              },
            ]}
          />
        )}
        <Animated.View
          style={{
            transform: [
              { translateY: bobY },
              { rotate: tilt.interpolate({ inputRange: [-4, 4], outputRange: ['-4deg', '4deg'] }) },
              { scale: pokePunch },
              { scaleX: squash },
              { scaleY: squash.interpolate({ inputRange: [1, 1.12], outputRange: [1, 0.9] }) },
            ],
          }}
        >
          <Image
            source={frames[frame]}
            style={{ width: size, height: size }}
            resizeMode="contain"
            fadeDuration={0}
          />
        </Animated.View>
      </View>
    </Pressable>
  );
}

/** Rising, twinkling stars shown behind the pet while it celebrates. */
function Sparkles({ size, star }: { size: number; star: ImageRequireSource }) {
  const stars = useRef(
    Array.from({ length: 5 }, (_, i) => ({
      left: 8 + i * 19,
      delay: i * 320,
      drift: (i % 2 === 0 ? 1 : -1) * 14,
      anim: new Animated.Value(0),
    }))
  ).current;

  useEffect(() => {
    const loops = stars.map(({ anim, delay }) => {
      const loop = Animated.loop(
        Animated.sequence([
          Animated.delay(delay),
          Animated.timing(anim, {
            toValue: 1,
            duration: 1700,
            easing: Easing.linear,
            useNativeDriver: true,
          }),
          Animated.timing(anim, { toValue: 0, duration: 0, useNativeDriver: true }),
        ])
      );
      loop.start();
      return loop;
    });
    return () => loops.forEach((l) => l.stop());
  }, [stars]);

  return (
    <View style={[styles.sparkleLayer, { width: size, height: size }]} pointerEvents="none">
      {stars.map(({ anim, left, drift }, i) => (
        <Animated.Image
          key={i}
          source={star}
          style={[
            styles.star,
            {
              left: left as number,
              width: size * 0.13,
              height: size * 0.13,
              opacity: anim.interpolate({ inputRange: [0, 0.2, 0.8, 1], outputRange: [0, 1, 1, 0] }),
              transform: [
                {
                  translateY: anim.interpolate({ inputRange: [0, 1], outputRange: [0, -size * 0.55] }),
                },
                {
                  translateX: anim.interpolate({ inputRange: [0, 1], outputRange: [0, drift] }),
                },
              ],
            },
          ]}
        />
      ))}
    </View>
  );
}

const styles = StyleSheet.create({
  sparkleLayer: {
    position: 'absolute',
  },
  star: {
    position: 'absolute',
    bottom: '18%',
  },
  heart: {
    position: 'absolute',
    top: 0,
    zIndex: 1,
  },
});
